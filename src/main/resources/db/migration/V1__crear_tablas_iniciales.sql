-- ============================================================
-- Sistema de visualización de datos de trabajo infantil
-- Migración inicial de la base de datos
--
-- Esta migración crea la estructura inicial.
-- No inserta cuentas ni resultados estadísticos.
-- ============================================================


-- ============================================================
-- 1. ADMINISTRADORES
-- ============================================================

CREATE TABLE administrador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(160) NOT NULL,
    contrasena_hash VARCHAR(255) NOT NULL,

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acceso_en TIMESTAMP WITH TIME ZONE
);

-- Evita registrar el mismo correo con diferencias de mayúsculas.
CREATE UNIQUE INDEX uq_administrador_correo_normalizado
    ON administrador (LOWER(correo));


-- ============================================================
-- 2. PERIODOS
-- ============================================================

CREATE TABLE periodo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    anio INTEGER NOT NULL,
    trimestre INTEGER NOT NULL,

    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',

    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_periodo_anio_trimestre
        UNIQUE (anio, trimestre),

    CONSTRAINT ck_periodo_trimestre
        CHECK (trimestre BETWEEN 1 AND 4)
);


-- ============================================================
-- 3. TERRITORIOS
-- ============================================================

CREATE TABLE territorio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    codigo_fuente VARCHAR(30) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    tipo VARCHAR(40) NOT NULL,

    contorno_geojson TEXT,

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_territorio_codigo_fuente
        UNIQUE (codigo_fuente)
);


-- ============================================================
-- 4. INDICADORES
-- ============================================================

CREATE TABLE indicador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    codigo VARCHAR(60) NOT NULL,
    nombre VARCHAR(160) NOT NULL,
    descripcion TEXT NOT NULL,

    unidad VARCHAR(30) NOT NULL,

    regla_calculo TEXT NOT NULL,
    version_regla VARCHAR(20) NOT NULL DEFAULT '1.0',

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT uq_indicador_codigo_version
        UNIQUE (codigo, version_regla)
);


-- ============================================================
-- 5. CARGAS DE DATOS
-- ============================================================

CREATE TABLE carga_datos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    administrador_id BIGINT NOT NULL,
    periodo_id BIGINT NOT NULL,

    nombre_archivo VARCHAR(255) NOT NULL,

    estado VARCHAR(20) NOT NULL DEFAULT 'RECIBIDA',
    vigente BOOLEAN NOT NULL DEFAULT FALSE,

    registros_totales INTEGER NOT NULL DEFAULT 0,
    registros_pasto INTEGER NOT NULL DEFAULT 0,
    registros_validos INTEGER NOT NULL DEFAULT 0,
    registros_invalidos INTEGER NOT NULL DEFAULT 0,

    mensaje_resultado TEXT,

    iniciado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finalizado_en TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_carga_administrador
        FOREIGN KEY (administrador_id)
        REFERENCES administrador (id),

    CONSTRAINT fk_carga_periodo
        FOREIGN KEY (periodo_id)
        REFERENCES periodo (id),

    -- La V2 reemplaza esta restricción y agrega VALIDADA.
    CONSTRAINT ck_carga_estado
        CHECK (
            estado IN (
                'RECIBIDA',
                'VALIDANDO',
                'PROCESANDO',
                'COMPLETADA',
                'FALLIDA'
            )
        )
);

-- Para cada periodo solo puede existir una carga vigente.
CREATE UNIQUE INDEX uq_carga_vigente_por_periodo
    ON carga_datos (periodo_id)
    WHERE vigente = TRUE;

CREATE INDEX idx_carga_periodo
    ON carga_datos (periodo_id);

CREATE INDEX idx_carga_administrador
    ON carga_datos (administrador_id);


-- ============================================================
-- 6. ERRORES DE CARGA
-- ============================================================

CREATE TABLE error_carga (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    carga_id BIGINT NOT NULL,

    numero_fila INTEGER,
    campo VARCHAR(100),
    valor_recibido TEXT,

    detalle TEXT NOT NULL,

    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_error_carga
        FOREIGN KEY (carga_id)
        REFERENCES carga_datos (id)
);

CREATE INDEX idx_error_carga
    ON error_carga (carga_id);


-- ============================================================
-- 7. RESULTADOS
-- ============================================================

CREATE TABLE resultado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    carga_id BIGINT NOT NULL,
    indicador_id BIGINT NOT NULL,
    territorio_id BIGINT NOT NULL,

    criterio_agrupacion VARCHAR(80) NOT NULL DEFAULT 'GENERAL',
    grupo VARCHAR(120) NOT NULL DEFAULT 'TOTAL',

    valor NUMERIC(24, 6),
    numerador NUMERIC(24, 6),
    denominador NUMERIC(24, 6),

    cantidad_muestra INTEGER,
    motivo_no_disponible TEXT,

    calculado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_resultado_carga
        FOREIGN KEY (carga_id)
        REFERENCES carga_datos (id),

    CONSTRAINT fk_resultado_indicador
        FOREIGN KEY (indicador_id)
        REFERENCES indicador (id),

    CONSTRAINT fk_resultado_territorio
        FOREIGN KEY (territorio_id)
        REFERENCES territorio (id),

    CONSTRAINT uq_resultado_agrupacion
        UNIQUE (
            carga_id,
            indicador_id,
            territorio_id,
            criterio_agrupacion,
            grupo
        )
);

CREATE INDEX idx_resultado_carga
    ON resultado (carga_id);

CREATE INDEX idx_resultado_indicador
    ON resultado (indicador_id);

CREATE INDEX idx_resultado_territorio
    ON resultado (territorio_id);